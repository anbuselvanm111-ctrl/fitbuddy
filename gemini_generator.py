import os

from dotenv import load_dotenv
from google import genai

load_dotenv()

client = genai.Client(
    api_key=os.getenv("GEMINI_API_KEY")
)

model = os.getenv(
    "GEMINI_MODEL",
    "gemini-3.8-flash"
)


def generate_workout_gemini(
    username,
    age,
    weight,
    goal,
    intensity
):
    prompt = f"""
Create a personalized 7-day fitness workout plan.

User:
Name: {username}
Age: {age}
Weight: {weight} kg
Fitness Goal: {goal}
Workout Intensity: {intensity}

For each day include:
- Day number and focus
- Warm-up
- Main workout
- Exercises with sets/reps or duration
- Rest time
- Cooldown or recovery tip

Make the plan clear, practical, structured, and easy to follow.
"""

    try:
        response = client.models.generate_content(
            model=model,
            contents=prompt
        )

        return response.text

    except Exception:
        return f"""
FitBuddy Demo Workout Plan

User: {username}
Age: {age}
Weight: {weight} kg
Goal: {goal}
Intensity: {intensity}

Day 1 - Full Body
• Warm-up: 5 minutes
• Chair Squats: 2 × 10
• Wall Push-ups: 2 × 10
• Standing Knee Raises: 2 × 10
• Cooldown: 5 minutes

Day 2 - Walking
• Warm-up: 5 minutes
• Brisk Walking: 30 minutes
• Cooldown: 5 minutes

Day 3 - Lower Body
• Warm-up: 5 minutes
• Supported Lunges: 2 × 8
• Calf Raises: 2 × 15
• Glute Bridges: 2 × 10
• Cooldown: 5 minutes

Day 4 - Active Recovery
• Easy Walking: 20 minutes
• Gentle stretching: 10 minutes

Day 5 - Upper Body
• Wall Push-ups: 2 × 10
• Shoulder movements: 2 × 10
• Light cardio: 10 minutes

Day 6 - Full Body
• Brisk Walking: 20 minutes
• Bodyweight Squats: 2 × 10
• Standing Leg Raises: 2 × 10
• Cooldown: 5 minutes

Day 7 - Rest
• Full rest
• Light walking if comfortable
• Focus on hydration and sleep

This is a demo plan generated by FitBuddy.
"""